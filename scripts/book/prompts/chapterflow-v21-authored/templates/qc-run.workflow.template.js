export const meta = {
  name: 'qc-run',
  description: 'Semantic QC of a book: tooled blind-key verification, dual-lens bar reads, cross-chapter sweep, adversarial adjudication, then qc-attest',
  phases: [
    { title: 'Blind keys', detail: 'derive every quiz answer from quiz-blind output only, verify mechanically' },
    { title: 'Bar read', detail: 'two independent lenses per chapter against the publishable-bar rubric' },
    { title: 'Sweep', detail: 'one cross-chapter read for skeletons, persona drift, repeated shapes' },
    { title: 'Adjudicate', detail: 'adversarially verify every corruption-class claim before it counts' },
    { title: 'Attest', detail: 'record the verdicts via qc-attest (reviewer = this harness run)' },
  ],
}

