// ── Phase 1+2: per-chapter pipeline (blind keys → two bar-read lenses) ───────

const LENSES = [
  {
    key: 'editorial',
    axes: ['example_coherence', 'prose_coherence', 'memorable_line_quality', 'plan_actionability'],
    brief: 'You are a skeptical senior EDITOR judging craft: do the scenes, prose tiers, memorable lines, and plan read as finished, human, non-templated writing?',
  },
  {
    key: 'pedagogy',
    axes: ['quiz_distractor_quality', 'card_learning_value', 'factual_accuracy'],
    brief: 'You are a skeptical LEARNING DESIGNER judging whether this chapter actually teaches: distractor quality, card learning value, factual/framework accuracy against the source.',
  },
]

function lensPrompt(lens, c) {
  const rubricBlock = lens.axes.map((a) => `- ${a} [weight ${CONFIG.weights[a]}]: ${CONFIG.rubric[a]}`).join('\n')
  return `${lens.brief}

Chapter: ${c.file}
Source sidecar (ground truth where present): ${c.sidecar ?? 'NONE ON DISK — mark factual checks "could not verify", never silently pass'}
${CONFIG.goldFile ? `CALIBRATION ANCHOR: first skim ${CONFIG.goldFile} — that is what an 85+/PUBLISHABLE chapter reads like. Score relative to it.` : ''}

Score ONLY these axes, each 0..1, per these exact rubric definitions (they include the false-positive guards a clean book relies on — apply them):
${rubricBlock}

Every hit needs a VERBATIM quote and unitId (e.g. "example[2].scenario", "breakdown.deepRead", "card03.back"). Mark corruption=true only for corruption-tier defects as the rubric defines them. Do NOT check quiz answer keys — that is verified mechanically elsewhere.${lens.key === 'pedagogy' ? '\nAlso return booleans: grounded (≥2 real hardSpecifics from the sidecar appear meaningfully), frameworkComplete (named multi-step tools enumerated completely/correctly), cardsAnswerFronts (every back answers its front), distractorsReal (no junk-prefix/format-identifiable distractors).' : ''}
Do not write any files. Be the reviewer the QC-SESSION prompt warns about: scene-skeleton templating and cards-not-answering-fronts are THE historically most-missed defects.`
}

phase('Blind keys')
const perChapter = await pipeline(
  CONFIG.chapters,
  (c) =>
    agent(
      `Verify this chapter's quiz answer key WITHOUT ever seeing it. HARD RULES: do NOT open ${c.file} or any chapter file; do NOT read state/qc. Work only from the commands below${c.sidecar ? ` and the source sidecar (${c.sidecar}), which contains the source facts but no answer key — reading it is allowed and encouraged` : ''}.

1. Run: ${CLI} quiz-blind ${c.file}
   It prints the questions as {questionIndex, prompt, choices[]} with the key stripped.
2. For EACH question, derive the correct choice index yourself from the prompt + choices${c.sidecar ? ' + the sidecar facts' : ''}. FP-guard: a misconception keyed correct IS correct when the stem asks for it ("What is the simplistic reading to avoid?").
3. Run: ${CLI} quiz-verify ${c.file} --answers "<qIndex>:<choiceIndex>,..." with your full derivation (every question — partial coverage fails).
4. Report quiz-verify's result: allMatch, and each MISMATCH with your reasoning. A mismatch is a CLAIM at this stage (it may be your error) — adjudication is separate; do not re-litigate here.`,
      { label: `keys:ch${c.n}`, phase: 'Blind keys', schema: KEYS_SCHEMA },
    ),
  (keys, c) =>
    parallel(
      LENSES.map((lens) => () =>
        agent(lensPrompt(lens, c), { label: `read-${lens.key}:ch${c.n}`, phase: 'Bar read', schema: LENS_SCHEMA }),
      ),
    ).then((lenses) => ({ c, keys, lenses: lenses.filter(Boolean) })),
)

// ── Phase 3: cross-chapter sweep (the defect class per-chapter reads miss) ──

phase('Sweep')
const sweep = await agent(
  `Cross-chapter templating sweep for "${CONFIG.bookId}" — read ALL of these chapter files (they are siblings of one book):
${CONFIG.chapters.map((c) => `- ${c.file}`).join('\n')}

Per-chapter reviewers structurally cannot see what repeats ACROSS chapters. You are the only stage that can. Look for exactly these classes (each finding needs a verbatim quote + every chapter number involved):
1. scene_skeleton — example scenes sharing one frame across chapters ("[Name] does X at [time] in [place]; must decide A or B"), even with different nouns. THE most-missed defect historically.
2. persona_drift — the same protagonist name used as different people across chapters/sections.
3. repeated_unit — card backs, plan shapes, quiz openers, hooks, or breakdown paragraphs that are near-identical across chapters.
4. location_stamping — one location stamped as the setting across many chapters' examples.
FP-guards: clock times INSIDE coherent, different scenes are fine; a consistent pedagogical opener is a convention when content differs; shared CONCEPT terms are the book's vocabulary, not templating. Report only what a paying reader would notice as copy-paste.`,
  { label: 'sweep', phase: 'Sweep', schema: SWEEP_SCHEMA },
)

// ── Merge: provisional verdicts (publishableBar reduction, weights/floors from CONFIG) ──

const sweepByChapter = new Map()
for (const f of (sweep?.findings ?? [])) {
  for (const n of f.chapterNumbers) {
    if (!sweepByChapter.has(n)) sweepByChapter.set(n, [])
    sweepByChapter.get(n).push(f)
  }
}

function provisionalFor(r) {
  const axes = []
  for (const lens of r.lenses) for (const a of lens.axes) axes.push(a)
  const keyScore = r.keys
    ? Math.max(0, 1 - (r.keys.mismatches.length / Math.max(1, CONFIG.quizCounts[r.c.n] ?? 9)))
    : 0
  axes.push({ axis: 'quiz_key_correctness', score: keyScore, hits: [] })
  const corruptionClaims = []
  for (const m of r.keys?.mismatches ?? []) {
    corruptionClaims.push({ kind: 'key', chapter: r.c, m })
  }
  for (const lens of r.lenses) {
    for (const a of lens.axes) {
      for (const h of a.hits) {
        if (h.corruption && CONFIG.corruptionAxes.includes(a.axis)) {
          corruptionClaims.push({ kind: 'axis', chapter: r.c, axis: a.axis, hit: h })
        }
      }
    }
  }
  return { axes, corruptionClaims }
}

// ── Phase 4: adjudicate every corruption-class claim before it counts ────────

phase('Adjudicate')
const adjudicated = await parallel(
  perChapter.filter(Boolean).map((r) => () => {
    const prov = provisionalFor(r)
    return parallel(
      prov.corruptionClaims.map((claim) => () =>
        agent(
          claim.kind === 'key'
            ? `Adjudicate a claimed WRONG QUIZ KEY in ${claim.chapter.file}, question index ${claim.m.questionIndex}. A blind reviewer derived choice ${claim.m.derivedIndex}; the key says ${claim.m.keyedIndex}. Their reasoning: ${JSON.stringify(claim.m.reasoning).slice(0, 400)}.
Independently: run \`${CLI} quiz-blind ${claim.chapter.file}\`, derive YOUR answer for question ${claim.m.questionIndex} from prompt+choices${claim.chapter.sidecar ? ` + the sidecar ${claim.chapter.sidecar}` : ''} WITHOUT opening the chapter file, then open the chapter file and read that question's keyed choice AND its explanation. upheld=true ONLY if the key is genuinely wrong (your derivation AND the explanation's own logic disagree with correctIndex). A defensible key with a hard distractor → upheld=false. Default to upheld=false if uncertain.`
            : `Adjudicate a claimed ${claim.axis} CORRUPTION in ${claim.chapter.file}: unit ${claim.hit.unitId}, defect "${claim.hit.defect}", quote: ${JSON.stringify(claim.hit.quote).slice(0, 300)}.
Rubric (with its FP-guards — apply them): ${CONFIG.rubric[claim.axis]}
Read the actual unit in context. upheld=true ONLY if the quote is real (verbatim or near), the defect matches the rubric's corruption tier, and no FP-guard excuses it. Default to upheld=false if uncertain.`,
          { label: `adjudicate:ch${r.c.n}`, phase: 'Adjudicate', schema: ADJUDICATE_SCHEMA },
        ).then((v) => ({ claim, upheld: !!v?.upheld, note: v?.note ?? '' })),
      ),
    ).then((verdicts) => ({ r, prov, verdicts: verdicts.filter(Boolean) }))
  }),
)

function finalVerdict(entry) {
  const { r, prov, verdicts } = entry
  const upheldKeys = verdicts.filter((v) => v.claim.kind === 'key' && v.upheld)
  const upheldAxis = verdicts.filter((v) => v.claim.kind === 'axis' && v.upheld)
  const sweepHits = sweepByChapter.get(r.c.n) ?? []
  // publishableBar's hard rule: DID NOT RUN is never a pass. If any lens agent
  // died (rate limit, error), the chapter was not fully read — a keys-only
  // "overall" would print 100 and look perfect. Cap at REVISE with an explicit
  // incomplete marker so the operator re-runs instead of trusting an artifact.
  const incomplete = !r.keys || r.lenses.length < LENSES.length
  // Weighted overall (mirror of publishableBar.weightedOverall, weights from CONFIG)
  let num = 0, den = 0
  for (const a of prov.axes) {
    const w = CONFIG.weights[a.axis] ?? 0
    num += w * Math.max(0, Math.min(1, a.score))
    den += w
  }
  const overall = den === 0 ? 0 : Math.round((num / den) * 100)
  // HARD RULE 1: confirmed corruption is a veto — the average never launders it.
  let verdict
  if (upheldKeys.length > 0 || upheldAxis.length > 0) verdict = 'CORRUPTION'
  // HARD RULE 2: publishable ≠ not-corrupt; sweep templating AND an incomplete
  // read both cap at REVISE (a chapter nobody fully read cannot be attested
  // PUBLISHABLE).
  else if (incomplete || overall < CONFIG.publishableFloor || prov.axes.some((a) => a.score < CONFIG.axisFloor) || sweepHits.length > 0) verdict = 'REVISE'
  else verdict = 'PUBLISHABLE'
  const booleans = Object.assign({ grounded: true, frameworkComplete: true, cardsAnswerFronts: true, distractorsReal: true }, ...r.lenses.map((l) => l.booleans ?? {}))
  const dims = {
    keysCorrect: upheldKeys.length === 0,
    grounded: !!booleans.grounded,
    nonTemplated: upheldAxis.length === 0 && sweepHits.length === 0,
    frameworkComplete: !!booleans.frameworkComplete,
    cardsAnswerFronts: !!booleans.cardsAnswerFronts,
    distractorsReal: !!booleans.distractorsReal,
  }
  const noteBits = [
    incomplete ? `INCOMPLETE READ (${r.lenses.length}/${LENSES.length} lenses${r.keys ? '' : ', keys missing'}) — re-run qc-run for this chapter` : `overall=${overall}`,
    upheldKeys.length ? `${upheldKeys.length} confirmed wrong key(s)` : null,
    upheldAxis.length ? `${upheldAxis.length} confirmed corruption hit(s)` : null,
    sweepHits.length ? `cross-chapter: ${sweepHits.map((f) => f.kind).join('/')}` : null,
    r.lenses.map((l) => l.notes).filter(Boolean).join(' | ').slice(0, 120) || null,
  ].filter(Boolean)
  return { n: r.c.n, file: r.c.file, verdict, overall: incomplete ? null : overall, dims, note: noteBits.join('; ').slice(0, 220), upheldKeys: upheldKeys.length }
}

const finals = adjudicated.filter(Boolean).map(finalVerdict)

// ── Phase 5: attest ──────────────────────────────────────────────────────────

phase('Attest')
log(`Verdicts: ${finals.map((f) => `ch${f.n}=${f.verdict}(${f.overall})`).join(' ')}`)
const attested = await parallel(
  finals.map((f) => () =>
    agent(
      `Record a QC verdict. Run EXACTLY this command and report its output verbatim:

${CLI} qc-attest ${f.file} --verdict ${f.verdict} --reviewer "${CONFIG.reviewer}" --dimensions "${Object.entries(f.dims).map(([k, v]) => `${k}=${v}`).join(',')}" --notes ${JSON.stringify(f.note)}

If it prints "QC attestation written" → attested=true. If it prints REFUSED (the self-attest guard: a PUBLISHABLE flip over an unchanged non-PUBLISHABLE verdict) → attested=false and include the full refusal in cliOutput; do NOT retry with --supersede — that override is the OPERATOR's call, not yours.`,
      { label: `attest:ch${f.n}`, phase: 'Attest', schema: ATTEST_SCHEMA },
    ),
  ),
)

const byVerdict = { PUBLISHABLE: [], REVISE: [], CORRUPTION: [] }
for (const f of finals) byVerdict[f.verdict].push(f.n)
log(`Attested ${attested.filter(Boolean).filter((a) => a.attested).length}/${finals.length} — PUBLISHABLE ${byVerdict.PUBLISHABLE.length}, REVISE ${byVerdict.REVISE.length}, CORRUPTION ${byVerdict.CORRUPTION.length}`)

return {
  bookId: CONFIG.bookId,
  byVerdict,
  perChapter: finals,
  sweepFindings: sweep?.findings ?? [],
  attested: attested.filter(Boolean).map((a) => ({ chapter: a.chapterNumber, attested: a.attested, output: a.cliOutput.slice(-200) })),
}
