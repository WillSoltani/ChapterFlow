// CONFIG carries the LIVE rubric/weights/floors from src/critics/semantic/
// publishableBar.ts at generation time, so prompts cannot drift from the code.
const CONFIG = __CONFIG__

const P = CONFIG.pipelineDir
const pad = (n) => String(n).padStart(2, '0')
const CLI = `cd ${P} && npx tsx src/cli.ts`

// ── Schemas ──────────────────────────────────────────────────────────────────

